"""Generate a monolithic CHIRP driver for the Radtel RT-950 Pro."""
from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Callable, Iterable, List, Sequence

MODULE_ORDER: Sequence[tuple[str, Path, Callable[[str], str]]] = (
    ("channel", Path("rt950pro/channel.py"), None),
    ("sections", Path("rt950pro/sections.py"), None),
    ("settings_api", Path("rt950pro/settings_api.py"), None),
    ("image", Path("rt950pro/image.py"), None),
    ("transport", Path("rt950pro/transport.py"), None),
    ("driver", Path("rt950pro/chirp_driver.py"), None),
)

HEADER = """CHIRP driver for the Radtel RT-950 Pro (generated).

This file was generated by `scripts/build_monolith.py`. Do not edit manually;
update the generator or the source modules under `rt950pro/` instead.
"""

